"""Database engine, sessions and the declarative base shared by every module.

One engine (connection pool) per process, created in the app lifespan. Each request gets its
own session through `get_session`; services decide when to commit, and anything uncommitted
is rolled back when the session closes.
"""

import datetime
import uuid
from collections.abc import AsyncIterator
from typing import Any, ClassVar

from fastapi import Request
from sqlalchemy import DateTime, MetaData, func, text
from sqlalchemy.ext.asyncio import (
    AsyncEngine,
    AsyncSession,
    async_sessionmaker,
    create_async_engine,
)
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column

from app.core.config import Settings

# Stable, predictable constraint names, so migrations can refer to them.
NAMING_CONVENTION = {
    "ix": "ix_%(column_0_label)s",
    "uq": "uq_%(table_name)s_%(column_0_name)s",
    "ck": "ck_%(table_name)s_%(constraint_name)s",
    "fk": "fk_%(table_name)s_%(column_0_name)s_%(referred_table_name)s",
    "pk": "pk_%(table_name)s",
}


class Base(DeclarativeBase):
    metadata = MetaData(naming_convention=NAMING_CONVENTION)
    type_annotation_map: ClassVar[dict[Any, Any]] = {  # Any: SQLAlchemy accepts any type key
        datetime.datetime: DateTime(timezone=True)
    }


def uuid_primary_key() -> Mapped[uuid.UUID]:
    """Time-ordered UUIDv7 generated by Postgres 18, so ids sort by creation."""
    return mapped_column(primary_key=True, server_default=text("uuidv7()"))


def created_at_column() -> Mapped[datetime.datetime]:
    return mapped_column(server_default=func.now())


def create_engine(settings: Settings) -> AsyncEngine:
    database = settings.database
    return create_async_engine(
        settings.database_url.get_secret_value(),
        pool_size=database.pool_size,
        max_overflow=database.max_overflow,
        pool_timeout=database.pool_timeout_seconds,
        pool_pre_ping=True,
    )


def create_session_factory(engine: AsyncEngine) -> async_sessionmaker[AsyncSession]:
    return async_sessionmaker(engine, expire_on_commit=False)


async def get_session(request: Request) -> AsyncIterator[AsyncSession]:
    """FastAPI dependency: one session per request, closed (and rolled back) afterwards."""
    session_factory: async_sessionmaker[AsyncSession] = request.app.state.session_factory
    async with session_factory() as session:
        yield session
